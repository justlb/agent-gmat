#!/usr/bin/env python3
"""Extract the human-readable RF-COMLINK reports from a calculated scenario."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import zipfile
from html.parser import HTMLParser
from pathlib import Path


class TextExtractor(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []

    def handle_data(self, data: str) -> None:
        value = " ".join(data.split())
        if value:
            self.parts.append(value)


def report_text(source: bytes) -> str:
    parser = TextExtractor()
    parser.feed(source.decode("utf-8", errors="replace"))
    return re.sub(r"\s+", " ", " ".join(parser.parts)).strip()


class TableExtractor(HTMLParser):
    """Read report tables without relying on RF-COMLINK's visual HTML."""
    def __init__(self) -> None:
        super().__init__()
        self.rows: list[list[str]] = []
        self._row: list[str] | None = None
        self._cell: list[str] | None = None

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "tr":
            self._row = []
        elif tag in {"td", "th"} and self._row is not None:
            self._cell = []

    def handle_data(self, data: str) -> None:
        if self._cell is not None:
            self._cell.append(data)

    def handle_endtag(self, tag: str) -> None:
        if tag in {"td", "th"} and self._cell is not None and self._row is not None:
            self._row.append(" ".join("".join(self._cell).split()))
            self._cell = None
        elif tag == "tr" and self._row is not None:
            if any(self._row):
                self.rows.append(self._row)
            self._row = None


def as_number(value: str) -> float | None:
    """Accept RF-COMLINK's French decimal comma and scientific notation."""
    match = re.search(r"[-+]?\d+(?:[,.]\d+)?(?:[Ee][-+]?\d+)?", value)
    if not match:
        return None
    try:
        return float(match.group(0).replace(",", "."))
    except ValueError:
        return None


def value_for_row(rows: list[list[str]], label: str) -> list[float | None] | None:
    for row in rows:
        if row and label.casefold() in row[0].casefold():
            return [as_number(value) for value in row[1:]]
    return None


def value_for_any_row(rows: list[list[str]], labels: tuple[str, ...]) -> list[float | None] | None:
    for label in labels:
        value = value_for_row(rows, label)
        if value is not None:
            return value
    return None


def report_link_name(report_path: str) -> str:
    name = Path(report_path).stem
    return re.sub(r"^\d+[_ -]*", "", name).replace("_", " ") or name


def case_values(values: list[float | None] | None) -> dict[str, float] | None:
    if not values or values[0] is None:
        return None
    result = {"nominal": values[0]}
    if len(values) > 1 and values[1] is not None:
        result["three_sigma"] = values[1]
    if len(values) > 2 and values[2] is not None:
        result["worst_case_rss"] = values[2]
    return result


def link_budget(report_path: str, source: bytes) -> dict[str, object] | None:
    """Extract the numerical RF link-budget table generated by RF-COMLINK.

    The report format contains several input tables followed by one Link Budget
    table.  Named rows are more stable than table indices across RF-COMLINK
    releases, so every value is located by its engineering label.
    """
    parser = TableExtractor()
    parser.feed(source.decode("utf-8", errors="replace"))
    rows = parser.rows
    margin = case_values(value_for_row(rows, "Data recovery margin"))
    achieved = case_values(value_for_any_row(rows, ("Acheived Eb/N0", "Achieved Eb/N0")))
    cn0 = case_values(value_for_row(rows, "C/N0"))
    if not margin and not achieved and not cn0:
        return None
    required = value_for_row(rows, "Required Eb/N0")
    frequency = value_for_row(rows, "Frequency")
    rate = value_for_row(rows, "Binary rate")
    link_type = next((row[1] for row in rows if len(row) > 1 and row[0].casefold().startswith("link type")), None)
    range_km = value_for_row(rows, "Range")
    elevation = value_for_row(rows, "Satellite elevation")
    temperature = value_for_row(rows, "System temperature Tsys (K)")
    worst_margin = (margin or {}).get("worst_case_rss", (margin or {}).get("nominal"))
    return {
        "link_name": report_link_name(report_path),
        "source_report": report_path,
        "link_type": link_type,
        "frequency_mhz": frequency[0] if frequency and frequency[0] is not None else None,
        "binary_rate_bps": rate[0] if rate and rate[0] is not None else None,
        "required_ebn0_db": required[0] if required and required[0] is not None else None,
        "range_km": range_km[0] if range_km and range_km[0] is not None else None,
        "elevation_deg": elevation[0] if elevation and elevation[0] is not None else None,
        "system_temperature_k": temperature[0] if temperature and temperature[0] is not None else None,
        "received_cn0_dbhz": cn0,
        "achieved_ebn0_db": achieved,
        "data_recovery_margin_db": margin,
        "status": "pass" if worst_margin is not None and worst_margin >= 0 else "fail" if worst_margin is not None else "unavailable",
    }


RESULT_FILE_SUFFIXES = {
    "_Receiver_C_per_N0_": "received_cn0_dbhz",
    "_Achieved_Eb_per_N0_": "achieved_ebn0_db",
    "_Eb_per_N0_Margin_": "data_recovery_margin_db",
    "_RF_VISIBILITY_": "visibility",
}


def result_file_identity(path: str) -> tuple[str, str] | None:
    """Return the RF link name and metric represented by an output CIC file."""
    filename = Path(path).name
    for marker, metric in RESULT_FILE_SUFFIXES.items():
        if marker in filename:
            return filename.split(marker, 1)[0], metric
    return None


def cic_samples(source: bytes) -> list[list[float]]:
    """Read finite RF-COMLINK result rows, ignoring the no-data sentinel."""
    samples: list[list[float]] = []
    for line in source.decode("utf-8", errors="replace").splitlines():
        fields = line.split()
        if len(fields) < 3:
            continue
        try:
            values = [float(value.replace(",", ".")) for value in fields[2:]]
        except ValueError:
            continue
        if values and all(abs(value) < 1e300 for value in values):
            samples.append(values)
    return samples


def average_cases(samples: list[list[float]]) -> dict[str, float] | None:
    if not samples:
        return None
    names = ("nominal", "three_sigma", "worst_case_rss")
    return {
        names[index]: sum(row[index] for row in samples if len(row) > index) / len(samples)
        for index in range(min(3, max(len(row) for row in samples)))
    }


def budgets_from_output_files(entries: list[tuple[str, bytes]]) -> list[dict[str, object]]:
    """Build auditable link summaries from RF-COMLINK's saved CIC outputs.

    The desktop application can save a scenario without an HTML report. Its
    calculated CIC files are still authoritative outputs: each contains the
    design, 3σ and worst-RSS values at every valid visibility sample.
    """
    grouped: dict[str, dict[str, object]] = {}
    for path, source in entries:
        identity = result_file_identity(path)
        if identity is None:
            continue
        link_name, metric = identity
        group = grouped.setdefault(link_name, {"files": [], "metrics": {}})
        group["files"].append(path)
        group["metrics"][metric] = cic_samples(source)

    budgets: list[dict[str, object]] = []
    for link_name, group in grouped.items():
        metrics = group["metrics"]
        # RF-COMLINK writes its no-visibility samples as a floating-point
        # sentinel. ``cic_samples`` has already removed those rows, so the
        # remaining values are exactly the valid RF-visibility intervals.
        margin_samples = metrics.get("data_recovery_margin_db", [])
        margin = average_cases(margin_samples)
        worst_margins = [row[2] if len(row) > 2 else row[0] for row in margin_samples if row]
        minimum_margin = min(worst_margins) if worst_margins else None
        budgets.append({
            "link_name": link_name,
            "source_data_files": group["files"],
            "received_cn0_dbhz": average_cases(metrics.get("received_cn0_dbhz", [])),
            "achieved_ebn0_db": average_cases(metrics.get("achieved_ebn0_db", [])),
            "data_recovery_margin_db": margin,
            "minimum_data_recovery_margin_db": minimum_margin,
            "visible_sample_count": len(margin_samples),
            "status": "pass" if minimum_margin is not None and minimum_margin >= 0 else "fail" if minimum_margin is not None else "unavailable",
        })
    return budgets


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--scenario", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    scenario = args.scenario.resolve()
    with zipfile.ZipFile(scenario) as archive:
        report_names = sorted(name for name in archive.namelist() if name.lower().startswith("reports/") and name.lower().endswith((".html", ".htm")))
        report_bytes = [(name, archive.read(name)) for name in report_names]
        reports = [{"path": name, "text": report_text(source)[:100_000]} for name, source in report_bytes]
        link_budgets = [budget for name, source in report_bytes if (budget := link_budget(name, source))]
        output_bytes = [(name, archive.read(name)) for name in archive.namelist() if name.lower().startswith("ephemeris/") and name.lower().endswith(".txt")]
        output_budgets = budgets_from_output_files(output_bytes)
        existing_names = {str(budget["link_name"]).casefold() for budget in link_budgets}
        link_budgets.extend(budget for budget in output_budgets if str(budget["link_name"]).casefold() not in existing_names)
        links = sorted(name for name in archive.namelist() if name.lower().startswith("links/") and name.lower().endswith(".xml"))

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps({
        "schema_version": 2,
        "scenario": scenario.name,
        "sha256": hashlib.sha256(scenario.read_bytes()).hexdigest(),
        "reports": reports,
        "link_budgets": link_budgets,
        "link_files": links,
    }, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
